export default function AmenitiesList({ amenities }: AmenitiesListProps) {
  // Normalizar amenities de la propiedad (remover guiones bajos, lowercase)
  const normalizedPropertyAmenities = amenities.map(a =>
    a.toLowerCase().replace(/_/g, ' ').trim()
  )

  return (
    <div>
      <h3 className="text-2xl font-bold text-accent mb-6">
        Servicios y comodidades
      </h3>
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
        {ALL_AMENITIES.map((amenity, index) => {
          // Verificar si alguna de las keys de DB coincide con las amenities de la propiedad
          const isAvailable = amenity.dbKeys.some(key =>
            normalizedPropertyAmenities.includes(key.toLowerCase().replace(/_/g, ' '))
          )

          return (
            <div
              key={index}
              className={`flex items-center gap-3 p-3 rounded-lg border transition-all ${
                isAvailable
                  ? 'bg-white border-gray-200 text-gray-900'
                  : 'bg-gray-50 border-gray-100 text-gray-400'
              }`}
            >
              <div className={isAvailable ? 'text-primary' : 'text-gray-300'}>
                {amenity.icon}
              </div>
              <span className={`text-sm font-medium ${isAvailable ? '' : 'line-through'}`}>
                {amenity.name}
              </span>
            </div>
          )
        })}
      </div>
    </div>
  )
}
